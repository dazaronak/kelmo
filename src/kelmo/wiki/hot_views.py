"""Generated HOT views: one Markdown file per project map plus a startup render of every mandatory
page, written beside the wiki in every publication.

What an agent must always see travels in instruction-file imports (CLAUDE.md, AGENTS.md), because a
startup hook cannot carry it: Claude Code caps each hook context string at 10,000 characters and moves
anything longer into a file the agent is never asked to read. A view is a pure function of the
registry being published and the page's own text, so it changes exactly when they do and never
needs a separate refresh.

A project view carries the map's own prose as the overview, its constraint facts in full, every
other fact of the map as a one-line trap (the first clause, with the full text on the map page),
then every open work page of the project as a WIP or Backlog row (title, priority, summary, link),
grouped under the topic page it hangs from. Nothing is dropped while the view fits its byte budget;
past it, rows degrade in a fixed order: Backlog summaries, Backlog counts, WIP H3 and unprioritized
rows, the trap index, WIP H2 summaries, and last WIP H1 summaries. Constraints and H1 titles never
degrade. A view still over budget after the last step is written with a marker on its second line,
never refused: a publication must not fail because a view grew, and the marker is what
`over_budget` and the doctor read.

A mandatory render is the page delivered whole at startup (person pages and every page holding a
mandatory or protected fact) without its frontmatter and without the rows of retired facts; the
wiki page itself keeps them.
"""
from __future__ import annotations

from pathlib import PurePosixPath
import re

from . import pages

HEADER_NOTE = '<!-- Generated by kelmo from {source}; edits are overwritten. -->'
OVER_BUDGET_NOTE = ('<!-- kelmo: view over budget by {over} bytes after every degradation step; '
                    'raise views_max_bytes or move facts off the map page. -->')
DEFAULT_MAX_BYTES = 48000
STUB_CHARS = 80
STUB_FLOOR = 30
MANDATORY_PREFIX = 'mandatory-'
PRIORITY_ORDER = {'H1': 0, 'H2': 1, 'H3': 2, '': 3}
SECTIONS = (('in-progress', 'WIP', 'wip'), ('backlog', 'Backlog', 'backlog'))
# Row modes per priority for WIP and Backlog, and the trap index mode, from nothing degraded to the
# last step. H1 titles and constraints are never degraded.
_FULL = {'H1': 'full', 'H2': 'full', 'H3': 'full', '': 'full'}
DEGRADE_STEPS = (
    (_FULL, _FULL, 'index'),
    (_FULL, {'H1': 'full', 'H2': 'compact', 'H3': 'compact', '': 'compact'}, 'index'),
    (_FULL, {'H1': 'full', 'H2': 'compact', 'H3': 'count', '': 'count'}, 'index'),
    (_FULL, {'H1': 'full', 'H2': 'count', 'H3': 'count', '': 'count'}, 'index'),
    ({'H1': 'full', 'H2': 'full', 'H3': 'compact', '': 'compact'}, {'H1': 'full', 'H2': 'count', 'H3': 'count', '': 'count'}, 'index'),
    ({'H1': 'full', 'H2': 'full', 'H3': 'count', '': 'count'}, {'H1': 'full', 'H2': 'count', 'H3': 'count', '': 'count'}, 'index'),
    ({'H1': 'full', 'H2': 'full', 'H3': 'count', '': 'count'}, {'H1': 'full', 'H2': 'count', 'H3': 'count', '': 'count'}, 'count'),
    ({'H1': 'full', 'H2': 'compact', 'H3': 'count', '': 'count'}, {'H1': 'compact', 'H2': 'count', 'H3': 'count', '': 'count'}, 'count'),
    ({'H1': 'full', 'H2': 'count', 'H3': 'count', '': 'count'}, {'H1': 'compact', 'H2': 'count', 'H3': 'count', '': 'count'}, 'count'),
    ({'H1': 'compact', 'H2': 'count', 'H3': 'count', '': 'count'}, {'H1': 'compact', 'H2': 'count', 'H3': 'count', '': 'count'}, 'count'),
)
_FRONTMATTER = re.compile(r'\A---\n.*?\n---\n+', re.DOTALL)
_RETIRED_ROW = re.compile(r'^- .*\[status: retired\].*$\n?', re.MULTILINE)


def view_name(project):
    return project + '.md'


def mandatory_name(target):
    """The startup render of one mandatory page: `hot/mandatory-<basename>`, flat beside the views."""
    return MANDATORY_PREFIX + PurePosixPath(target).name


def validate_output_names(registry, projects, *, mandatory=()):
    targets = set(pages.mandatory_paths(registry, registry['pages'])) | set(mandatory)
    reserved = {mandatory_name(target)[:-3] for target in targets}
    if set(projects) & (reserved | {'mandatory'}):
        raise ValueError('Generated HOT output name collision with mandatory memory')


def _wiki_id(target):
    return target[:-3] if target.endswith('.md') else target


def _demote(text):
    """The map's own prose one heading level lower, so the view keeps a single H1; a hand-written H1
    leading the prose repeats the view's own title and is left out."""
    text = re.sub(r'\A# [^\n]*\n*', '', text)
    return re.sub(r'^(#{1,5}) ', lambda match: '#' + match.group(1) + ' ', text, flags=re.MULTILINE)


def stub(text, limit=STUB_CHARS, floor=STUB_FLOOR):
    """The opening clauses of a fact, at most `limit` characters: enough to know the trap exists.

    Clauses end at `.`, `;` or `:`; they are taken until the stub reaches `floor`, so a lead-in such as
    `Decided in March:` is never the whole stub, then cut at `limit` with an ellipsis."""
    clauses = re.split(r'(?<=[.;:])\s', text.strip())
    first = clauses[0]
    for clause in clauses[1:]:
        if len(first) >= floor:
            break
        first += ' ' + clause
    if len(first) <= limit:
        return first
    return first[:limit - 1].rstrip() + '…'


def _facts(registry, target):
    """(constraint facts, other facts) of one page, retired left out, in key order."""
    constraints, others = [], []
    for _, fact in sorted(registry['facts'].items()):
        if fact['target'] != target or fact['status'] == 'retired':
            continue
        (constraints if fact.get('role') == 'constraint' else others).append(fact['text'])
    return constraints, others


def _open_pages(registry, project):
    """Open work pages of one project: (section, parent, priority, title, target, summary)."""
    result = []
    for target, entry in registry['pages'].items():
        if entry['kind'] != 'work' or pages.project_of(target) != project:
            continue
        status = pages.page_status(target, registry['facts'])
        if status not in ('in-progress', 'backlog'):
            continue
        result.append((status, entry.get('parent') or '', entry['priority'], entry['title'], target,
                       entry['summary']))
    return result


def _row(item, mode):
    _, _, priority, title, target, summary = item
    label = '- **' + title + '**' + (' (' + priority + ')' if priority else '')
    if mode == 'full' and summary and summary != title:
        return label + ' — ' + summary + ' — [[' + _wiki_id(target) + ']]'
    return label + ' — [[' + _wiki_id(target) + ']]'


def _section(registry, map_target, items, word, modes):
    """One WIP or Backlog section: rows under the map first, then one heading per parent topic, and
    one closing line counting the rows the step collapsed, by priority."""
    groups = {}
    collapsed = {}
    for item in items:
        if modes.get(item[2], 'full') == 'count':
            collapsed[item[2]] = collapsed.get(item[2], 0) + 1
            continue
        parent = item[1]
        key = '' if parent in ('', map_target) or parent not in registry['pages'] else parent
        groups.setdefault(key, []).append(item)
    lines = []
    for key in sorted(groups, key=lambda name: (name != '', registry['pages'].get(name, {}).get('title', ''))):
        if key:
            lines += ['', '### ' + registry['pages'][key]['title']]
        for item in sorted(groups[key], key=lambda row: (PRIORITY_ORDER.get(row[2], 3), row[3].lower())):
            lines.append(_row(item, modes.get(item[2], 'full')))
    if collapsed:
        buckets = ', '.join(f'{collapsed[priority]} {priority or "unprioritized"}'
                            for priority in ('H1', 'H2', 'H3', '') if collapsed.get(priority))
        lines += ['', f'- {sum(collapsed.values())} more {word} pages ({buckets}) — see [[{_wiki_id(map_target)}]]']
    return lines


def _compose(registry, map_target, overview, constraints, traps, items, step):
    wip_modes, backlog_modes, trap_mode = step
    parts = ['# ' + registry['pages'][map_target]['title'], HEADER_NOTE.format(source=map_target), '## Overview']
    if overview:
        parts.append(overview)
    if constraints:
        parts.append('### Constraints\n\n' + '\n'.join('- ' + text for text in constraints))
    if traps and trap_mode == 'index':
        parts.append('### Known traps (full text on [[' + _wiki_id(map_target) + ']])\n\n'
                     + '\n'.join('- ' + stub(text) for text in traps))
    elif traps:
        parts.append(f'### Known traps: {len(traps)} on [[{_wiki_id(map_target)}]]')
    for status, heading, word in SECTIONS:
        selected = [item for item in items if item[0] == status]
        if selected:
            modes = wip_modes if status == 'in-progress' else backlog_modes
            parts.append('## ' + heading + '\n\n'
                         + '\n'.join(_section(registry, map_target, selected, word, modes)).lstrip('\n'))
    return '\n\n'.join(parts) + '\n'


def render(registry, map_target, map_text, max_bytes=DEFAULT_MAX_BYTES):
    """The HOT view of one project map: the first degradation step whose text fits `max_bytes`, or
    the last step marked over budget."""
    overview = _demote(pages.unmanaged_text(map_text)) if map_text else ''
    constraints, traps = _facts(registry, map_target)
    items = _open_pages(registry, pages.project_of(map_target))
    text = ''
    for step in DEGRADE_STEPS:
        text = _compose(registry, map_target, overview, constraints, traps, items, step)
        if len(text.encode('utf-8')) <= max_bytes:
            return text
    over = len(text.encode('utf-8')) - max_bytes
    head, rest = text.split('\n', 1)
    return head + '\n' + OVER_BUDGET_NOTE.format(over=over) + '\n' + rest


def over_budget(text):
    """Bytes over budget recorded in a rendered view, or None when the view fit."""
    match = re.search(r'<!-- kelmo: view over budget by (\d+) bytes', text)
    return int(match.group(1)) if match else None


def render_mandatory(text):
    """A mandatory page as delivered at startup: no frontmatter, no retired rows; everything else
    byte for byte."""
    return _RETIRED_ROW.sub('', _FRONTMATTER.sub('', text, 1))


def project_maps(registry):
    return sorted(target for target, entry in registry['pages'].items()
                  if entry.get('layout') == 'project-map' and pages.project_of(target))


def _page_text(rendered_pages, wiki_root, target):
    path = wiki_root / PurePosixPath(target)
    text = rendered_pages.get(path)
    if text is None and path.is_file():
        text = path.read_bytes().decode('utf-8')
    return text


def render_all(registry, rendered_pages, wiki_root, hot_root, max_bytes=DEFAULT_MAX_BYTES, *, generation=None, selection=None):
    """{path: text} for every project map and every mandatory page, reading each page's text from
    this publication's rendering."""
    result = {}
    maps = project_maps(registry)
    names = [pages.project_of(target) for target in maps]
    if len(set(names)) != len(names) or 'mandatory' in names:
        raise ValueError('Generated HOT output name collision')
    if generation is not None:
        header = f'<!-- kelmo generation {generation} -->\n'
        known = {str(PurePosixPath(path.relative_to(wiki_root))) for path in rendered_pages
                 if path.is_relative_to(wiki_root)}
        known |= {target for target in registry['pages'] if (wiki_root / PurePosixPath(target)).is_file()}
        selection = selection or {}
        mandatory = []
        canonical_mandatory = set(pages.mandatory_paths(registry, known))
        mandatory_targets = list(dict.fromkeys([*pages.mandatory_paths(registry, known),
                                                *selection.get('pages', [])]))
        for target in mandatory_targets:
            text = _page_text(rendered_pages, wiki_root, target)
            if text is None:
                raise ValueError('Mandatory page is missing: ' + target)
            mandatory.append(render_mandatory(text) if target in canonical_mandatory else text)
        body = '\n\n'.join(mandatory)
        if body and not body.endswith('\n'):
            body += '\n'
        result[hot_root / 'mandatory.md'] = header + body
        targets = {pages.project_of(target): target for target in maps}
        for project in selection.get('projects', {}):
            targets.setdefault(project, None)
        validate_output_names(registry, targets, mandatory=canonical_mandatory)
        for project, target in targets.items():
            extras = ''
            extra = selection.get('projects', {}).get(project, {}).get('pages', [])
            for selected in dict.fromkeys(extra):
                if selected == target or selected in mandatory_targets:
                    continue
                content = _page_text(rendered_pages, wiki_root, selected)
                if content is None:
                    raise ValueError('Selected HOT page is missing: ' + selected)
                extras += '\n## Selected page: ' + selected + '\n\n' + content
            budget = max(0, max_bytes - len((header + extras).encode('utf-8')))
            view = (render(registry, target, _page_text(rendered_pages, wiki_root, target), budget)
                    if target else '# ' + project + '\n')
            view = re.sub(r'<!-- kelmo: view over budget by [^\n]*-->\n', '', view) + extras
            over = len((header + view).encode('utf-8')) - max_bytes
            if over > 0:
                view = OVER_BUDGET_NOTE.format(over=over) + '\n' + view
            result[hot_root / view_name(project)] = header + view
            result[hot_root / (project + '.full.md')] = header + body + ('\n' if body else '') + view
        aliases = {}
        for target in sorted(canonical_mandatory):
            aliases.setdefault(mandatory_name(target), []).append(target)
        for name, sources in aliases.items():
            result[hot_root / name] = header + '\n\n'.join(
                render_mandatory(_page_text(rendered_pages, wiki_root, source)) for source in sources)
        return result
    for target in maps:
        text = _page_text(rendered_pages, wiki_root, target)
        result[hot_root / view_name(pages.project_of(target))] = render(registry, target, text, max_bytes)
    known = {str(PurePosixPath(path.relative_to(wiki_root))) for path in rendered_pages if path.is_relative_to(wiki_root)}
    known |= {target for target in registry['pages'] if (wiki_root / PurePosixPath(target)).is_file()}
    for target in pages.mandatory_paths(registry, known):
        text = _page_text(rendered_pages, wiki_root, target)
        if text is not None:
            result[hot_root / mandatory_name(target)] = render_mandatory(text)
    return result
