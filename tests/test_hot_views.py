"""Generated per-project HOT views and the startup-hook size limit."""
import subprocess

import pytest

from kelmo.errors import KelmoError

MAP = 'projects/app/app.md'


def page(title, kind='work', layout='feature', parent='', priority='', summary=''):
    return {'title': title, 'kind': kind, 'layout': layout, 'parent': parent, 'priority': priority,
            'summary': summary, 'category': 'projects'}


def fact(target, text, status='active', role=None):
    return {'target': target, 'text': text, 'status': status, 'role': role}


def registry():
    pages = {
        MAP: page('App', 'hub', 'project-map'),
        'projects/app/search.md': page('Search', 'topic', 'topic', MAP),
        'projects/app/ranking.md': page('Fix ranking', parent='projects/app/search.md', priority='H1',
                                        summary='Ranking drops exact titles.'),
        'projects/app/filters.md': page('Add filters', parent='projects/app/search.md'),
        'projects/app/login.md': page('Login redesign', parent=MAP, priority='H2', summary='Plan approved.'),
        'projects/app/done.md': page('Shipped thing', parent=MAP, priority='H1', summary='Done.'),
        'projects/other/other.md': page('Other', 'hub', 'project-map'),
        'projects/other/task.md': page('Other task', parent='projects/other/other.md', priority='H1'),
    }
    facts = {
        'a': fact(MAP, 'The app runs on one server.'),
        'b': fact(MAP, 'Never deploy on Friday.', role='constraint'),
        'c': fact(MAP, 'An old retired line.', status='retired'),
        'd': fact('projects/app/ranking.md', 'Ranking work started.', 'in-progress'),
        'e': fact('projects/app/filters.md', 'Filters are planned.', 'backlog'),
        'f': fact('projects/app/login.md', 'Login is planned.', 'backlog'),
        'g': fact('projects/app/done.md', 'Shipped.', 'shipped'),
        'h': fact('projects/other/task.md', 'Other work.', 'in-progress'),
    }
    return {'pages': pages, 'facts': facts}


MAP_TEXT = '---\nkind: hub\n---\n\n# App\n\n## Architecture\n\nOne server.\n'


def test_view_carries_overview_constraints_traps_and_every_open_page_of_its_project():
    from kelmo.wiki import hot_views
    text = hot_views.render(registry(), MAP, MAP_TEXT)
    assert text.startswith('# App\n\n<!-- Generated by kelmo from projects/app/app.md;')
    assert '## Overview\n\n### Architecture\n\nOne server.' in text
    assert '\n## App\n' not in text, 'the map H1 is repeated inside the view'
    assert '### Constraints\n\n- Never deploy on Friday.' in text
    assert '### Known traps (full text on [[projects/app/app]])\n\n- The app runs on one server.' in text
    assert 'Current map' not in text
    assert 'An old retired line.' not in text
    wip, backlog = text.split('## WIP\n\n', 1)[1].split('## Backlog\n\n')
    assert '### Search\n- **Fix ranking** (H1) — Ranking drops exact titles. — [[projects/app/ranking]]' in wip
    assert backlog.startswith('- **Login redesign** (H2) — Plan approved. — [[projects/app/login]]')
    assert '### Search\n- **Add filters** — [[projects/app/filters]]' in backlog
    assert 'Shipped thing' not in text and 'Other task' not in text


def test_trap_is_the_first_clause_cut_at_eighty_characters():
    from kelmo.wiki import hot_views
    assert hot_views.stub('Short fact, long enough on its own. The rest of it.') == 'Short fact, long enough on its own.'
    assert hot_views.stub('Decided today: the stub keeps going. Not this.') == 'Decided today: the stub keeps going.'
    assert hot_views.stub('A rule: the detail follows; more detail.') == 'A rule: the detail follows; more detail.'
    long = 'word ' * 30
    cut = hot_views.stub(long)
    assert len(cut) == 80 and cut.endswith('…') and not cut[:-1].endswith(' ')
    value = registry()
    value['facts']['t'] = fact(MAP, 'Trap one is the first clause of this fact; the long explanation. Second sentence.')
    text = hot_views.render(value, MAP, MAP_TEXT)
    assert '- Trap one is the first clause of this fact;\n' in text and 'the long explanation' not in text


def crowded(backlog=40, wip=0):
    value = registry()
    for index in range(backlog):
        target = f'projects/app/item-{index:02}.md'
        value['pages'][target] = page(f'Item {index:02}', parent=MAP, summary='x' * 150)
        value['facts']['item' + str(index)] = fact(target, 'Open.', 'backlog')
    for index in range(wip):
        target = f'projects/app/wip-{index:02}.md'
        value['pages'][target] = page(f'Wip {index:02}', parent=MAP, priority='H3', summary='w' * 150)
        value['facts']['wip' + str(index)] = fact(target, 'Running.', 'in-progress')
    return value


def test_over_budget_view_degrades_backlog_before_wip_and_traps_before_h1():
    from kelmo.wiki import hot_views
    value = crowded(wip=10)
    for index in range(30):
        value['facts'][f'trap{index}'] = fact(MAP, f'Trap {index:02} of the map. Details.')
    full = hot_views.render(value, MAP, MAP_TEXT, max_bytes=1048576)
    assert full.count('x' * 150) == 40 and full.count('w' * 150) == 10
    compact = hot_views.render(value, MAP, MAP_TEXT, max_bytes=len(full.encode()) - 1)
    assert 'x' * 150 not in compact and '- **Item 00** — [[projects/app/item-00]]' in compact
    assert compact.count('w' * 150) == 10, 'WIP lost summaries before the Backlog did'
    # Shrinking the budget: the first budget at which each loss appears orders the steps.
    events = {'backlog summaries': lambda t: 'x' * 150 not in t,
              'backlog count': lambda t: '41 unprioritized) — see [[projects/app/app]]' in t,
              'wip summaries': lambda t: 'w' * 150 not in t,
              'wip count': lambda t: '- 10 more wip pages (10 H3) — see [[projects/app/app]]' in t,
              'trap count': lambda t: '### Known traps: 31 on [[projects/app/app]]' in t,
              'h1 summary': lambda t: 'Ranking drops exact titles.' not in t}
    first_seen = {}
    for budget in range(len(full.encode()), 300, -25):
        text = hot_views.render(value, MAP, MAP_TEXT, max_bytes=budget)
        over = hot_views.over_budget(text)
        assert over is not None or len(text.encode()) <= budget
        assert '- Never deploy on Friday.' in text and '**Fix ranking** (H1)' in text
        for name, seen in events.items():
            if seen(text):
                first_seen.setdefault(name, budget)
            else:
                assert name not in first_seen, f'{name} came back at a smaller budget'
        if over is not None:
            break
    assert list(first_seen) == list(events), 'degradation ran in the wrong order'
    assert over is not None, 'the loop never reached the last step'


def test_view_that_cannot_fit_is_written_with_a_marker_not_refused():
    from kelmo.wiki import hot_views
    value = crowded()
    text = hot_views.render(value, MAP, MAP_TEXT, max_bytes=300)
    lines = text.split('\n')
    assert lines[0] == '# App'
    assert lines[1].startswith('<!-- kelmo: view over budget by ') and lines[1].endswith('-->')
    assert hot_views.over_budget(text) == len(text.encode()) - len(lines[1].encode()) - 1 - 300
    assert '- Never deploy on Friday.' in text and '**Fix ranking** (H1) — [[projects/app/ranking]]' in text
    assert 'Ranking drops exact titles.' not in text, 'the last step still carries H1 summaries'
    assert hot_views.over_budget(hot_views.render(value, MAP, MAP_TEXT)) is None


def test_mandatory_render_drops_frontmatter_and_retired_rows_only():
    from kelmo.wiki import hot_views
    page_text = ('---\nkind: hub\nlayout: person\n---\n\n# User Profile\n\n## Facts\n\n'
                 '- Live fact. [f:1] [source:a]\n'
                 '- Gone fact. [f:2] [source:b] [status: retired]\n'
                 '- Shipped fact. [f:3] [source:c] [status: shipped]\n\n## See Also\n\n- [[life]]\n')
    assert hot_views.render_mandatory(page_text) == (
        '# User Profile\n\n## Facts\n\n- Live fact. [f:1] [source:a]\n'
        '- Shipped fact. [f:3] [source:c] [status: shipped]\n\n## See Also\n\n- [[life]]\n')
    assert hot_views.render_mandatory('# Bare\n\nNo frontmatter.\n') == '# Bare\n\nNo frontmatter.\n'


def test_one_view_per_project_map_and_one_render_per_mandatory_page(tmp_path):
    from kelmo.wiki import hot_views
    value = registry()
    value['pages']['person.md'] = page('Person', 'hub', 'person')
    value['pages']['life/preferences.md'] = page('Preferences', 'hub', 'topic')
    value['facts']['p'] = fact('person.md', 'Rule.')
    value['facts']['q'] = dict(fact('life/preferences.md', 'Mandatory pref.'), mandatory=True)
    value['facts']['r'] = fact('life/preferences.md', 'Old pref.', status='retired')
    wiki = tmp_path / 'wiki'
    (wiki / 'life').mkdir(parents=True)
    (wiki / 'life/preferences.md').write_text('---\nkind: hub\n---\n\n# Preferences\n\n- Mandatory pref. [f:q]\n'
                                              '- Old pref. [f:r] [status: retired]\n')
    rendered = {wiki / 'person.md': '---\nkind: hub\n---\n\n# Person\n\n- Rule. [f:p]\n'}
    views = hot_views.render_all(value, rendered, wiki, tmp_path / 'hot')
    assert sorted(path.name for path in views) == ['app.md', 'mandatory-person.md', 'mandatory-preferences.md',
                                                   'other.md']
    assert '**Other task** (H1)' in views[tmp_path / 'hot/other.md']
    assert views[tmp_path / 'hot/mandatory-person.md'] == '# Person\n\n- Rule. [f:p]\n'
    assert views[tmp_path / 'hot/mandatory-preferences.md'] == '# Preferences\n\n- Mandatory pref. [f:q]\n'
    assert views[tmp_path / 'hot/app.md'] == hot_views.render(value, MAP, '')


def test_views_configuration_is_validated(tmp_path):
    from kelmo.hot import validate
    assert 'views' not in validate({}, tmp_path)
    assert validate({'views': True}, tmp_path)['views'] == {'max_bytes': 48000}
    assert validate({'views': True, 'views_max_bytes': 8192}, tmp_path)['views'] == {'max_bytes': 8192}
    for raw in ({'views': 'yes'}, {'views': True, 'views_max_bytes': 10}):
        with pytest.raises(KelmoError, match='views'):
            validate(raw, tmp_path)


def test_startup_context_keeps_short_context_and_points_past_the_hook_limit():
    from kelmo.hot import HOOK_CONTEXT_LIMIT, startup_context
    short = 'Kelmo knowledge generation 7: current.\n\n## person.md\n\nbody'
    assert startup_context(short) == short
    long = 'Kelmo knowledge generation 8: current.\n\n## person.md\n\n' + 'y' * 20000
    result = startup_context(long)
    assert len(result) <= HOOK_CONTEXT_LIMIT
    assert result.startswith('Kelmo knowledge generation 8: current.\n\n')
    assert 'knowledge/hot' in result and 'graph_read' in result and 'y' * 100 not in result


ADOPTED_PAGES = {MAP: dict(page_id='app', layout='project-map', title='App'),
                 'person.md': dict(page_id='person', layout='person', title='Person')}


def viewed_store(tmp_path, monkeypatch, views=True):
    from kelmo.service import Service
    for key, value in {'GIT_AUTHOR_NAME': 'Synthetic Fixture', 'GIT_COMMITTER_NAME': 'Synthetic Fixture',
                       'GIT_AUTHOR_EMAIL': 'fixture@example.invalid',
                       'GIT_COMMITTER_EMAIL': 'fixture@example.invalid',
                       'GIT_CONFIG_NOSYSTEM': '1', 'GIT_CONFIG_GLOBAL': '/dev/null'}.items():
        monkeypatch.setenv(key, value)
    root = tmp_path / 'vault'
    Service.initialize(root, 'fixture-node')
    toml = root / 'kelmo.toml'
    toml.write_text(toml.read_text() + '\n[hot]\nviews = ' + ('true' if views else 'false') + '\n')
    return root


@pytest.mark.parametrize('views', [True, False])
def test_interrupted_publication_with_views_recovers_to_the_old_tree(tmp_path, monkeypatch, views):
    import registry_seed
    from kelmo.wiki import engine
    root = viewed_store(tmp_path, monkeypatch, views)
    real = engine.git

    def failing(repository, *args, **kwargs):
        if args[0] == 'commit' and '--only' in args:
            raise KelmoError('E_GIT', 'Synthetic commit failure')
        return real(repository, *args, **kwargs)

    monkeypatch.setattr(engine, 'git', failing)
    with pytest.raises(KelmoError, match='Synthetic commit failure'):
        registry_seed.seed(root, pages_settings=ADOPTED_PAGES)
    assert not engine.transaction_path(root).exists(), 'recovery refused the view path and kept the marker'
    assert not (root / 'knowledge/hot/app.md').exists()


@pytest.mark.parametrize('boundary', ['normal', 'before-commit', 'after-commit'])
def test_bound_layout_publishes_and_recovers_views(tmp_path, monkeypatch, boundary):
    """The server's layout: schema 2, the knowledge repository bound apart from the control root."""
    import copy
    import json
    import registry_seed
    from kelmo.wiki import engine, pages
    from test_nested_layout import PublicationInterrupted, enroll, make_layout, page_entry
    from test_wiki_roots import git
    layout = make_layout(tmp_path)
    toml = layout.control / 'kelmo.toml'
    toml.write_text(toml.read_text() + '\n[hot]\nviews = true\n')
    enroll(layout)
    sequence = json.loads((layout.vault / 'knowledge/provenance/generation.json').read_bytes())['sequence']
    fixture_map = 'projects/viewed/viewed.md'
    registry = copy.deepcopy(layout.registry)
    registry['pages'][fixture_map] = page_entry(layout_name='project-map', kind='hub', category='projects',
                                                title='Fixture', summary='', priority='', page_id='fixture')
    view = layout.vault / 'knowledge/hot/viewed.md'
    if boundary != 'normal':
        original_git, original_recover, calls = engine.git, engine._recover_transaction, []

        def failpoint(root, *args, **kwargs):
            if boundary == 'before-commit' and args[0] == 'add':
                raise PublicationInterrupted
            result = original_git(root, *args, **kwargs)
            if boundary == 'after-commit' and args[0] == 'commit':
                raise PublicationInterrupted
            return result

        def defer_cleanup(root):
            # The first call is the interrupted publication's own cleanup: deferred, so its marker stays on disk.
            calls.append(root)
            return None if len(calls) == 1 else original_recover(root)

        with monkeypatch.context() as scoped:
            scoped.setattr(engine, 'git', failpoint)
            scoped.setattr(engine, '_recover_transaction', defer_cleanup)
            with pytest.raises(PublicationInterrupted):
                registry_seed.publish(layout.control, registry, 'chore: Publish fixture map')
        assert engine.transaction_path(layout.control).is_file()
        engine.recover_transaction(layout.control)
        assert not engine.transaction_path(layout.control).exists()
        if boundary == 'before-commit':
            assert not view.exists()
            assert (layout.vault / 'knowledge/hot/fixture.md').read_bytes() == b'Existing HOT.\n'
            registry_seed.publish(layout.control, registry, 'chore: Publish fixture map')
    else:
        registry_seed.publish(layout.control, registry, 'chore: Publish fixture map')
    assert view.read_text().startswith(f'<!-- kelmo generation {sequence + 1} -->\n# Fixture\n')
    assert (layout.vault / 'knowledge/hot/fixture.md').read_bytes() == b'Existing HOT.\n'
    assert git(layout.vault, 'status', '--porcelain', '--', 'knowledge/hot') == ''
    assert pages.KnowledgeReader(engine.Config.load(layout.control)).generation().publication_id == sequence + 1


@pytest.mark.parametrize('edited', [False, True])
def test_published_view_with_another_header_is_regenerated_but_a_local_edit_is_refused(tmp_path, monkeypatch, edited):
    """A store imported from another writer keeps views whose first line Kelmo did not write."""
    import copy
    import re
    import registry_seed
    from kelmo.wiki import engine, hot_views
    from test_nested_layout import enroll, make_layout, page_entry
    layout = make_layout(tmp_path)
    toml = layout.control / 'kelmo.toml'
    toml.write_text(toml.read_text() + '\n[hot]\nviews = true\n')
    enroll(layout)
    registry = copy.deepcopy(layout.registry)
    registry['pages']['projects/viewed/viewed.md'] = page_entry(layout_name='project-map', kind='hub', category='projects',
                                                                title='Fixture', summary='', priority='', page_id='fixture')
    original = hot_views.render_all

    def other_header(*args, **kwargs):
        return {path: re.sub(r'\A<!-- kelmo generation', '<!-- other generation', text)
                for path, text in original(*args, **kwargs).items()}

    with monkeypatch.context() as scoped:
        scoped.setattr(hot_views, 'render_all', other_header)
        registry_seed.publish(layout.control, registry, 'chore: Publish fixture map')
    view = layout.vault / 'knowledge/hot/viewed.md'
    assert view.read_text().startswith('<!-- other generation ')
    registry['pages']['projects/second/second.md'] = page_entry(layout_name='project-map', kind='hub', category='projects',
                                                                title='Second', summary='', priority='', page_id='second')
    if edited:
        view.write_text(view.read_text() + 'Edited by hand.\n')
        with pytest.raises(engine.OwnershipConflict):
            registry_seed.publish(layout.control, registry, 'chore: Publish second map')
        assert view.read_text().endswith('Edited by hand.\n')
    else:
        registry_seed.publish(layout.control, registry, 'chore: Publish second map')
        assert view.read_text().startswith('<!-- kelmo generation ')


def test_publication_writes_views_in_the_same_commit_and_generation(tmp_path, monkeypatch):
    import registry_seed
    from kelmo import doctor
    root = viewed_store(tmp_path, monkeypatch)
    registry_seed.seed(root, pages_settings=ADOPTED_PAGES)
    view = root / 'knowledge/hot/app.md'
    assert view.read_text().splitlines()[0].startswith('<!-- kelmo generation ')
    assert view.read_text().splitlines()[1] == '# App'
    tracked = subprocess.run(['git', '-C', str(root), 'status', '--porcelain', '--', 'knowledge/hot'],
                             capture_output=True, text=True, check=True).stdout
    assert tracked == ''
    head = subprocess.run(['git', '-C', str(root), 'show', '--name-only', '--format=', 'HEAD'],
                          capture_output=True, text=True, check=True).stdout.split()
    assert 'knowledge/hot/app.md' in head
    report = doctor.diagnose(root)
    assert report['checks']['wiki_consistency'] and report['checks']['wiki_committed']
